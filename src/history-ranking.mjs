const changesById = new Map(historyRankChanges.map((change) => [change.id, change]));

export function defaultHistoryRankInfo(row) {
  const sourceRank = HISTORY_RANKS.includes(row?.level) ? row.level : null;
  const id = typeof row?.id === 'number'
    ? row.id
    : typeof row?.id === 'string' && /^[1-9]\d*$/.test(row.id) ? Number(row.id) : NaN;
  const change = Number.isSafeInteger(id) && id > 0 && id <= 1000 ? changesById.get(id) : null;
  if (change && change.event === row?.event && change.fromRank === sourceRank) {
    return { rank: change.rank, reason: change.reason, reviewed: true };
  }
  if (sourceRank) {
    return {
      rank: sourceRank,
      reason: '元データのランクを使用しています。この項目には個別の補正を適用していません。',
      reviewed: false,
    };
  }
  return {
    rank: 'B',
    reason: '元データに有効なランクがないため、仮にBで表示しています。内容の優先度は未確認です。',
    reviewed: false,
  };
}
